#!/usr/bin/env python3
"""Reproduce the CI project: archive build configuration + current app tree."""
from pathlib import Path
import shutil
import sys
import zipfile

repo = Path(__file__).resolve().parent.parent
requested = Path(sys.argv[1]) if len(sys.argv) == 2 else repo / 'source'
dest = requested.absolute()
if dest.is_symlink() or dest.resolve() == repo or dest.resolve() in repo.parents:
    raise SystemExit('Choose a generated build directory, not the repository or its parent')
dest = dest.resolve()
marker = dest / '.mercedesdoctor-generated'
if dest.exists() and any(dest.iterdir()) and not marker.is_file():
    raise SystemExit('Refusing to overwrite a nonempty directory not created by this tool')
if dest.exists() and any(p.is_symlink() for p in dest.rglob('*')):
    raise SystemExit('Refusing a generated directory containing symlinks')
with zipfile.ZipFile(repo / 'MercedesDoctorAI_cloudbuild_v0.1-1.zip') as archive:
    if archive.testzip() is not None:
        raise SystemExit('Archive CRC failure')
    for item in archive.infolist():
        if not (dest / item.filename).resolve().is_relative_to(dest):
            raise SystemExit('Unsafe archive path')
    dest.mkdir(parents=True, exist_ok=True)
    marker.write_text('Generated by tools/prepare_project.py; do not edit here.\n')
    archive.extractall(dest)
# This location is owned by the generator; remove old/deleted archived app sources.
if (dest / 'app' / 'src').exists():
    shutil.rmtree(dest / 'app' / 'src')
shutil.copytree(repo / 'app' / 'src', dest / 'app' / 'src')
shutil.copy2(repo / 'app' / 'build.gradle.kts', dest / 'app' / 'build.gradle.kts')
print(f'Prepared Android project at {dest}')
